-- Vista principal de artículos con categoría, stock y precio activo
-- LATERAL evita ORA-01799 (outer-join no permite subquery en ON clause)
CREATE OR REPLACE VIEW VW_ARTICULOS AS
SELECT A.ID_ARTICULO,
       A.CODIGO_ARTICULO,
       A.CODIGO_BARRA_ARTICULO,
       A.NOMBRE_ARTICULO,
       A.DESCRIPCION_ARTICULO,
       A.TIPO_ARTICULO,
       A.PESO_ARTICULO,
       A.STOCK_MINIMO,
       A.STOCK_MAXIMO,
       A.ESTADO_ARTICULO,
       A.MANEJA_LOTE_ARTICULO,
       A.MANEJA_SERIE_ARTICULO,
       A.ID_CATEGORIA_ARTICULO,
       CA.NOMBRE_CATEGORIA_ARTICULO,
       NVL(SA.CANTIDAD_DISPONIBLE_STOCK_ARTICULO, 0) AS STOCK_DISPONIBLE,
       NVL(SA.COSTO_PROMEDIO_STOCK_ARTICULO, 0)      AS COSTO_PROMEDIO,
       NVL(LP.PRECIO, 0)                             AS PRECIO,
       NVL(LP.DESCUENTO_MAX, 0)                      AS DESCUENTO_MAX
FROM   ARTICULO A
LEFT JOIN CATEGORIAS_ARTICULO CA
       ON CA.ID_CATEGORIAS_ARTICULO = A.ID_CATEGORIA_ARTICULO
LEFT JOIN STOCK_ARTICULO SA
       ON SA.ID_ARTICULO = A.ID_ARTICULO
LEFT JOIN LATERAL (
    SELECT LPD.PRECIO_LISTA_PRECIOS_DET         AS PRECIO,
           LPD.DESCUENTO_MAX_LISTA_PRECIOS_DET  AS DESCUENTO_MAX
    FROM   LISTA_PRECIOS_DET LPD
    WHERE  LPD.ID_ARTICULO = A.ID_ARTICULO
      AND  LPD.ID_LISTA_PRECIOS = (
               SELECT LPH.ID_LISTA_PRECIOS
               FROM   LISTA_PRECIOS LPH
               WHERE  EXISTS (
                          SELECT 1 FROM LISTA_PRECIOS_DET X
                           WHERE X.ID_LISTA_PRECIOS = LPH.ID_LISTA_PRECIOS
                             AND X.ID_ARTICULO = A.ID_ARTICULO)
               ORDER BY CASE
                            WHEN LPH.FECHA_DESDE_LISTA_PRECIOS <= SYSDATE
                             AND (LPH.FECHA_HASTA_LISTA_PRECIOS IS NULL
                                  OR LPH.FECHA_HASTA_LISTA_PRECIOS >= SYSDATE)
                            THEN 0 ELSE 1
                        END,
                        LPH.FECHA_DESDE_LISTA_PRECIOS DESC,
                        LPH.ID_LISTA_PRECIOS DESC
               FETCH FIRST 1 ROW ONLY)
    FETCH FIRST 1 ROW ONLY
) LP ON (1=1);
/

