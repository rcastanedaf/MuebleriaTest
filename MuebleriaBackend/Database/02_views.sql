CREATE OR REPLACE VIEW VW_LOGIN_USUARIO AS
SELECT U.ID_USUARIO,
       U.USERNAME_USUARIO,
       U.PASSWORD_USUARIO,
       U.EMAIL_USUARIO,
       U.ESTADO_USUARIO,
       U.ID_SUCURSAL,
       R.NOMBRE_ROL,
       C.ID_CLIENTE
FROM   USUARIOS U
JOIN   ROLES R    ON R.ID_ROL = U.ID_ROL
LEFT JOIN CLIENTE C ON LOWER(C.EMAIL_CLIENTE) = LOWER(U.EMAIL_USUARIO);
/

