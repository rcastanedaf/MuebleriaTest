-- Actualiza la fecha de último acceso al hacer login
CREATE OR REPLACE PROCEDURE SP_USR_UPD_ACCESO(
    p_id_usuario IN USUARIOS.ID_USUARIO%TYPE
) AS
BEGIN
    UPDATE USUARIOS
       SET ULTIMO_ACCESO_USUARIO = SYSTIMESTAMP
     WHERE ID_USUARIO = p_id_usuario;
END SP_USR_UPD_ACCESO;
/

