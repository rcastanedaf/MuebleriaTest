-- UPSERT de precio en lista de precios activa (usado en edición de artículo)
CREATE OR REPLACE PROCEDURE SP_PRECIO_UPSERT(
    p_id_articulo IN NUMBER,
    p_precio      IN NUMBER
) AS
    v_id_lista NUMBER;
    v_count    NUMBER;
BEGIN
    -- 1. Buscar lista activa por fecha
    BEGIN
        SELECT ID_LISTA_PRECIOS INTO v_id_lista
          FROM LISTA_PRECIOS
         WHERE FECHA_DESDE_LISTA_PRECIOS <= SYSDATE
           AND (FECHA_HASTA_LISTA_PRECIOS IS NULL OR FECHA_HASTA_LISTA_PRECIOS >= SYSDATE)
         ORDER BY FECHA_DESDE_LISTA_PRECIOS DESC, ID_LISTA_PRECIOS ASC
         FETCH FIRST 1 ROW ONLY;
    EXCEPTION
        WHEN NO_DATA_FOUND THEN
            -- 2. Si no hay activa, buscar la lista más reciente que ya contiene el artículo
            BEGIN
                SELECT ID_LISTA_PRECIOS INTO v_id_lista
                  FROM LISTA_PRECIOS LPH
                 WHERE EXISTS (SELECT 1 FROM LISTA_PRECIOS_DET LPD
                                WHERE LPD.ID_LISTA_PRECIOS = LPH.ID_LISTA_PRECIOS
                                  AND LPD.ID_ARTICULO = p_id_articulo)
                 ORDER BY LPH.FECHA_DESDE_LISTA_PRECIOS DESC, LPH.ID_LISTA_PRECIOS DESC
                 FETCH FIRST 1 ROW ONLY;
            EXCEPTION
                WHEN NO_DATA_FOUND THEN
                    -- 3. Cualquier lista disponible
                    BEGIN
                        SELECT ID_LISTA_PRECIOS INTO v_id_lista
                          FROM LISTA_PRECIOS
                         ORDER BY FECHA_DESDE_LISTA_PRECIOS DESC, ID_LISTA_PRECIOS DESC
                         FETCH FIRST 1 ROW ONLY;
                    EXCEPTION
                        WHEN NO_DATA_FOUND THEN
                            RETURN; -- Sin lista de precios, no hacer nada
                    END;
            END;
    END;

    SELECT COUNT(*) INTO v_count
      FROM LISTA_PRECIOS_DET
     WHERE ID_ARTICULO = p_id_articulo AND ID_LISTA_PRECIOS = v_id_lista;

    IF v_count > 0 THEN
        UPDATE LISTA_PRECIOS_DET
           SET PRECIO_LISTA_PRECIOS_DET = p_precio
         WHERE ID_ARTICULO = p_id_articulo AND ID_LISTA_PRECIOS = v_id_lista;
    ELSE
        INSERT INTO LISTA_PRECIOS_DET(ID_LISTA_PRECIOS, ID_ARTICULO,
                                       PRECIO_LISTA_PRECIOS_DET, DESCUENTO_MAX_LISTA_PRECIOS_DET)
        VALUES (v_id_lista, p_id_articulo, p_precio, 0);
    END IF;
END SP_PRECIO_UPSERT;
/

